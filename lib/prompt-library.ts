export function getPromptTemplatesByCategory(c: PromptCategory): PromptTemplate[] {
  return promptTemplates.filter((item) => item.category === c);
}

export function searchPromptTemplates(keyword: string): PromptTemplate[] {
  const key = keyword.trim().toLowerCase();
  if (key === '') {
    return promptTemplates;
  }
  return promptTemplates.filter(
    (item) =>
      item.title.toLowerCase().includes(key) ||
      item.scene.toLowerCase().includes(key) ||
      item.prompt.toLowerCase().includes(key),
  );
}
