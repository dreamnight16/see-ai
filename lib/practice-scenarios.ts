/**
 * 练习场里的任务。每个任务给一个真实场景，让用户自己写一遍提示词，
 * 然后由 prompt-coach 用本地规则给出反馈——不需要联网，也不需要 API Key。
 *
 * mustHaves 里的 id 必须能在 lib/prompt-coach.ts 的 DETECTORS 里找到，
 * 用来告诉用户「这一项你漏了」。有测试盯着这件事。
 */
export interface PracticeScenario {
  id: string;
  title: string;
  /** 显示在卡片上的小标签 */
  tag: string;
  /** 归属轨道，用在推荐和配色上 */
  track: TrackId;
  icon: string;
  /** 把处境说清楚，用户要基于它来写 */
  situation: string;
  /** 这次要它帮你干的那件事 */
  goal: string;
  /** 合格的一句话应该覆盖哪些要素 */
  mustHaves: string[];
  /** 帮人下笔的开头，直接填在输入框里 */
  starter: string;
  /** 参考版本，用户写完可以对一下 */
  samplePrompt: string;
  /** 对照范例时该看什么 */
  closeLook: string;
  /** 一句提醒，通常是个坑 */
  warning?: string;
}

