export function getScenario(id: string): PracticeScenario | undefined {
  return practiceScenarios.find((s) => s.id === id);
}

/** 找出场景要求的、但用户这句提示词里没有覆盖到的规则 id */
export function missingMustHaves(scenario: PracticeScenario, hitIds: string[]): string[] {
  const hit = new Set(hitIds);
  return scenario.mustHaves.filter((id) => !hit.has(id));
}
