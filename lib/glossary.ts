/** 按分组取词，返回顺序跟 glossaryTerms 里的一致 */
export function getTermsByGroup(g: GlossaryGroup): GlossaryTerm[] {
  return glossaryTerms.filter((t) => t.group === g);
}

/** 在名词、英文和解释里做不区分大小写的包含匹配，关键词为空时返回全部 */
export function searchGlossary(keyword: string): GlossaryTerm[] {
  const q = keyword.trim().toLowerCase();
  if (q === "") return [...glossaryTerms];
  return glossaryTerms.filter((t) => {
    const haystack = [t.term, t.en ?? "", t.plain].join(" ").toLowerCase();
    return haystack.includes(q);
  });
}
